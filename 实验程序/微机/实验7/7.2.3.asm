DAPORT EQU 0FEFFH
	ORG 0000H
	AJMP START
	ORG 0100H
	START: MOV DPTR, #DAPORT
	MOV A, #00H
LOOP1:MOV R0,#3
	DLP1: MOVX @DPTR,A
	INC A
	CJNE A, #0FFH,DLP1
	DLP2: DEC A
	MOVX @DPTR,A
	CJNE A, #00H,DLP2
	DJNZ R0,DLP1
LOOP2:MOV R2, #3
	D1:MOVX @DPTR, A 
	INC A
	CJNE A, #0FFH, D1
	DJNZ R2, D1
	SJMP LOOP1
	END

