ORG 0000H
	    LJMP MAIN
	    ORG 0100H
MAIN:	MOV P1, #0FFH
NEXT:   MOV R5, #10
		MOV DPTR, #0FE03H
    	MOV A, #00H
		MOVX @DPTR, A
LOOP:	DJNZ R5, LOOP
WAIT:	JB P3.3, WAIT
        MOVX A, @DPTR
		CPL A
		MOV P1, A
		LCALL DELAY
		SJMP NEXT
DELAY: MOV R7, #30H
DLP1:  MOV R6, #0F0H
DLP2:  DJNZ R6, DLP2
	   DJNZ R7, DLP1
	   RET
       END
